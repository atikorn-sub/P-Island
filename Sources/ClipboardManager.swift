import AppKit
import UniformTypeIdentifiers

struct ClipItem: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(URL)
        case files([URL])
    }

    let id = UUID()
    let content: Content
    let date: Date
    let sourceApp: String?
}

/// Remembers recent copies. Kept in memory only (images in a temp folder that is wiped at launch),
/// and skips anything a password manager marks as concealed or transient.
final class ClipboardManager: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var lastCopiedID: UUID?

    var isEnabled: () -> Bool = { true }

    static let limit = 40
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let imageDir: URL

    init() {
        imageDir = FileManager.default.temporaryDirectory.appendingPathComponent("PIsland-Clipboard", isDirectory: true)
        try? FileManager.default.removeItem(at: imageDir)
        try? FileManager.default.createDirectory(at: imageDir, withIntermediateDirectories: true)
        let t = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.content {
        case .text(let s):
            pb.setString(s, forType: .string)
        case .image(let url):
            if let image = NSImage(contentsOf: url) { pb.writeObjects([image]) }
        case .files(let urls):
            pb.writeObjects(urls as [NSURL])
        }
        lastCopiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles(of: item)
    }

    func clear() {
        items.forEach(deleteFiles)
        items.removeAll()
    }

    func dragProvider(for item: ClipItem) -> NSItemProvider {
        switch item.content {
        case .text(let s): return NSItemProvider(object: s as NSString)
        case .image(let url): return NSItemProvider(contentsOf: url) ?? NSItemProvider()
        case .files(let urls): return urls.first.flatMap { NSItemProvider(contentsOf: $0) } ?? NSItemProvider()
        }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        guard isEnabled() else { return }
        let types = pb.types ?? []
        if types.contains(where: { Self.skippedTypes.contains($0.rawValue) }) { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(.files(urls), source: source)
        } else if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(.text(text), source: source)
        } else if types.contains(.png) || types.contains(.tiff), let image = NSImage(pasteboard: pb),
                  let url = saveImage(image) {
            add(.image(url), source: source)
        }
    }

    private func add(_ content: ClipItem.Content, source: String?) {
        // Copying something already in the list moves it back to the top.
        if let existing = items.first(where: { $0.content == content }) {
            items.removeAll { $0.id == existing.id }
        }
        items.insert(ClipItem(content: content, date: Date(), sourceApp: source), at: 0)
        while items.count > Self.limit {
            deleteFiles(of: items.removeLast())
        }
    }

    private func saveImage(_ image: NSImage) -> URL? {
        guard let tiff = image.tiffRepresentation,
              let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) else { return nil }
        let url = imageDir.appendingPathComponent(UUID().uuidString).appendingPathExtension("png")
        return (try? png.write(to: url)) != nil ? url : nil
    }

    private func deleteFiles(of item: ClipItem) {
        if case .image(let url) = item.content { try? FileManager.default.removeItem(at: url) }
    }
}
